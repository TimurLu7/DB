SELECT 
    Заказы.ID_заказа,
    Клиенты.Фамилия,
    Товары.Название,
    "Состав заказа".Количество,
    Товары.Цена,
    CAST(LEFT(Товары.Цена, CHARINDEX(' ', Товары.Цена) - 1)AS DECIMAL(10,1)) * "Состав заказа".Количество AS "Общая стоимость"
FROM 
    Заказы
    INNER JOIN Клиенты ON Заказы."Код клиента" = Клиенты.ID_клиента
    INNER JOIN "Состав заказа" ON Заказы.ID_заказа = "Состав заказа"."Код заказа"
    INNER JOIN Товары ON "Состав заказа"."Код товара" = Товары.ID_товара