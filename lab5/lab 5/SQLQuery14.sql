SELECT 
    Клиенты.Фамилия,
    Клиенты.Имя
FROM Клиенты
WHERE Клиенты.ID_клиента IN (
    SELECT DISTINCT Заказы.[Код клиента]
    FROM Заказы
    INNER JOIN [Состав заказа] ON Заказы.ID_заказа = [Состав заказа].[Код заказа]
    WHERE [Состав заказа].[Код товара] = (
        SELECT ID_товара FROM Товары WHERE Название = 'Мяч'
    )
);