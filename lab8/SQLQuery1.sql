SELECT 
    v.Наименование AS "Вид нематериальных активов",
    SUM(k.Балансовая_стоимость) AS "Балансовая стоимость",
    SUM(h.Амортизация_за_месяц) AS "Амортизационные отчисления",
    SUM(h.Остаточная_стоимость_на_конец) AS "Остаточная стоимость"
FROM [Учетная карта активов] k
JOIN [Виды активов] v ON k.Код_вида = v.Код_вида
JOIN [История амортизации] h ON k.Инвентарный_номер = h.Инвентарный_номер
WHERE h.Месяц = (
    SELECT MAX(Месяц) 
    FROM [История амортизации] 
    WHERE Инвентарный_номер = k.Инвентарный_номер
)
GROUP BY v.Наименование;