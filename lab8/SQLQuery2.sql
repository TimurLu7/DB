SELECT 
    k.Инвентарный_номер,
    k.Название AS "Наименование",
    v.Наименование AS "Вид",
    k.Дата_ввода AS "Месяц и год ввода",
    k.Годовая_норма_амортизации AS "Норма амортизации",
    k.Балансовая_стоимость,
    h.Амортизация_за_месяц AS "Амортизационные отчисления",
    h.Остаточная_стоимость_на_конец AS "Остаточная стоимость"
FROM [Учетная карта активов] k
JOIN [Виды активов] v ON k.Код_вида = v.Код_вида
JOIN [История амортизации] h ON k.Инвентарный_номер = h.Инвентарный_номер
WHERE k.Код_лица = 2
    AND h.Месяц = (
        SELECT MAX(Месяц) 
        FROM [История амортизации] 
        WHERE Инвентарный_номер = k.Инвентарный_номер
    )
ORDER BY k.Инвентарный_номер;