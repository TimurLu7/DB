SELECT 
    Инвентарный_номер,
    Месяц,
    Амортизация_за_месяц,
    LAG(Амортизация_за_месяц, 1, 0) OVER (PARTITION BY Инвентарный_номер ORDER BY Месяц) AS Амортизация_месяц_назад,
    Амортизация_за_месяц - LAG(Амортизация_за_месяц, 1, 0) OVER (PARTITION BY Инвентарный_номер ORDER BY Месяц) AS Изменение
FROM [История амортизации]
ORDER BY Инвентарный_номер, Месяц;